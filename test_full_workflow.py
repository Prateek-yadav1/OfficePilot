"""Run the complete OfficePilot workflow with local Ollama LLMs.

ADK and CrewAI agent responses are generated by local Llama 3.1, not by a
scripted model. Email/calendar data, PostgreSQL-backed document retrieval, the
research fixture, and the MCP task server remain local/mock components.

For this test harness only, a CLI approval gate replaces ADK's native tool
confirmation wrapper so the custom Workflow does not have to resume a stopped
invocation. The production action_executor.py is not modified.
"""

import asyncio
import os
import time
import uuid
from datetime import date, timedelta
from pathlib import Path
from typing import Any

from dotenv import load_dotenv

PROJECT_ROOT = Path(__file__).resolve().parent
load_dotenv(PROJECT_ROOT / ".env")

# Force local models for this test before importing agents (their model objects
# are constructed during import). This prevents accidental OpenRouter calls.
os.environ["LLM_PROVIDER"] = "ollama"
os.environ.setdefault("OLLAMA_API_BASE", "http://127.0.0.1:11434")
os.environ.setdefault(
    "OLLAMA_OPENAI_BASE_URL",
    "http://127.0.0.1:11434/v1",
)
os.environ.setdefault("OLLAMA_MODEL", "llama3.1")
os.environ.setdefault("CREWAI_OLLAMA_MODEL", "llama3.1:latest")

from google.adk.runners import Runner
from google.adk.sessions import InMemorySessionService
from google.adk.tools import FunctionTool
from google.genai import types
from google.adk.workflow import Workflow

from backend.agents.action_executor import (
    action_executor_agent,
    execute_followup_task_via_mcp,
)
from backend.agents.workflow import root_agent


CLIENT = "ABC Technologies"
TODAY = date.today()
TOMORROW = TODAY + timedelta(days=1)
FOLLOWUP_DETAILS = (
    "Confirm the next meeting date and follow up on clearer deployment milestones."
)
ACTUAL_MCP_RESULT: dict[str, Any] | None = None


async def approved_local_mcp_action(client: str, task_details: str) -> dict[str, Any]:
    """Ask the user before invoking the local MCP mock task server."""
    global ACTUAL_MCP_RESULT

    print("\n" + "=" * 78)
    print("HUMAN APPROVAL REQUIRED — LOCAL MCP MOCK ACTION")
    print("=" * 78)
    print(f"Client: {client}")
    print(f"Proposed task: {task_details}")

    try:
        answer = input("Approve this local mock task? (yes/no): ").strip().lower()
    except EOFError:
        answer = "no"

    if answer not in {"yes", "y"}:
        ACTUAL_MCP_RESULT = {
            "status": "rejected",
            "message": "The task was rejected. MCP was not called.",
        }
        print("\nACTUAL MCP RESULT:")
        print(ACTUAL_MCP_RESULT)
        return ACTUAL_MCP_RESULT

    try:
        ACTUAL_MCP_RESULT = await execute_followup_task_via_mcp(
            client=client,
            task_details=task_details,
            tenant_id=os.getenv("OFFICEPILOT_LOCAL_TENANT_ID", ""),
            user_id=os.getenv("OFFICEPILOT_LOCAL_USER_ID", ""),
        )
    except Exception as exc:  # Keep failures explicit; never report false success.
        ACTUAL_MCP_RESULT = {
            "status": "error",
            "message": f"MCP execution failed: {type(exc).__name__}: {exc}",
        }

    print("\nACTUAL MCP RESULT:")
    print(ACTUAL_MCP_RESULT)
    return ACTUAL_MCP_RESULT


def show_event(event) -> None:
    """Print LLM text and tool calls/results as the workflow progresses."""
    content = getattr(event, "content", None)
    if not content or not content.parts:
        return

    for part in content.parts:
        if part.function_call:
            print(
                f"\n[{event.author}] TOOL CALL: {part.function_call.name} "
                f"{part.function_call.args}"
            )
        elif part.function_response:
            print(
                f"\n[{event.author}] TOOL RESULT: "
                f"{part.function_response.response}"
            )
        elif part.text:
            print(f"\n[{event.author}] {part.text}")


async def main() -> None:
    # Override the native require_confirmation tool only for this CLI test.
    # The production action_executor.py remains unchanged.
    action_executor_agent.tools = [FunctionTool(func=approved_local_mcp_action)]

        # Rebuild the workflow after replacing the action executor tool.
    local_workflow = Workflow(
        name="officepilot_local_llm_workflow",
        description=root_agent.description,
        edges=root_agent.edges,
    )

    print("\n" + "=" * 78)
    print("OFFICEPILOT — FULL WORKFLOW WITH LOCAL LLAMA 3.1")
    print("=" * 78)
    print(f"Client: {CLIENT}")
    print(f"Today: {TODAY} | Requested meeting date: {TOMORROW}")
    print("ADK model: Ollama / Llama 3.1")
    print("CrewAI model: Ollama / Llama 3.1")
    print("Groq calls: disabled for this test")
    print("Email/calendar/document data and MCP action service: local components")
    print("CrewAI research data source: local mock research fixture")
    print("Agent responses: generated live by local LLMs (not scripted)")

    session_service = InMemorySessionService()
    user_id = "officepilot_local_user"
    tenant_id = os.getenv("OFFICEPILOT_LOCAL_TENANT_ID", "").strip()
    if not tenant_id:
        raise RuntimeError("Set OFFICEPILOT_LOCAL_TENANT_ID before running.")
    session_id = str(uuid.uuid4())
    app_name = local_workflow.name

    await session_service.create_session(
        app_name=app_name,
        user_id=user_id,
        session_id=session_id,
        state={
            "user_id": os.getenv(
                "OFFICEPILOT_LOCAL_USER_ID",
                user_id,
            ),
            "tenant_id": tenant_id,
            "original_request": f"Prepare me for tomorrow's meeting with {CLIENT}.",
            "client_name": CLIENT,
            "information_status": (
                "Check whether the next meeting is confirmed and identify "
                "deployment milestones, ownership, and previous deployment concerns."
            ),
        },
    )

    runner = Runner(
        agent=local_workflow,
        app_name=app_name,
        session_service=session_service,
)

    user_message = types.Content(
        role="user",
        parts=[
            types.Part.from_text(
                text=(
                    f"Prepare me for tomorrow's meeting with {CLIENT}. "
                    f"Today is {TODAY}; tomorrow is {TOMORROW}. "
                    "Use the available email, calendar, and document tools. "
                    "Research missing details, prepare a briefing, validate it, "
                    "and propose a follow-up action only if appropriate. "
                    "Do not invent a meeting time if the calendar does not confirm one."
                )
            )
        ],
    )

    # Benchmark wall-clock workflow execution, including human approval wait.
    benchmark_started = time.perf_counter()
    metrics = {
        "events": 0,
        "model_responses": 0,
        "prompt_tokens": 0,
        "output_tokens": 0,
        "total_tokens": 0,
        "tool_calls": 0,
        "tool_responses": 0,
        "errors": 0,
    }

    print("\\nSTARTING WORKFLOW…")
    async for event in runner.run_async(
        user_id=user_id,
        session_id=session_id,
        new_message=user_message,
    ):
        metrics["events"] += 1

        usage = getattr(event, "usage_metadata", None)
        if usage is not None:
            metrics["model_responses"] += 1
            metrics["prompt_tokens"] += int(
                getattr(usage, "prompt_token_count", 0) or 0
            )
            metrics["output_tokens"] += int(
                getattr(usage, "candidates_token_count", 0) or 0
            )
            metrics["total_tokens"] += int(
                getattr(usage, "total_token_count", 0) or 0
            )

        if getattr(event, "error_code", None):
            metrics["errors"] += 1

        content = getattr(event, "content", None)
        for part in getattr(content, "parts", []) or []:
            if getattr(part, "function_call", None):
                metrics["tool_calls"] += 1
            if getattr(part, "function_response", None):
                metrics["tool_responses"] += 1

        show_event(event)

    benchmark_elapsed = time.perf_counter() - benchmark_started

    print("\\n" + "=" * 78)
    print("OFFICEPILOT PERFORMANCE BENCHMARK")
    print("=" * 78)
    print(f"End-to-end wall time: {benchmark_elapsed:.2f} seconds")
    print("Note: wall time includes time spent waiting for human approval.")
    print(f"ADK events observed: {metrics['events']}")
    print(f"ADK model responses with usage data: {metrics['model_responses']}")
    print(f"ADK prompt tokens observed: {metrics['prompt_tokens']}")
    print(f"ADK output tokens observed: {metrics['output_tokens']}")
    print(f"ADK total tokens observed: {metrics['total_tokens']}")
    print(f"Tool calls observed: {metrics['tool_calls']}")
    print(f"Tool responses observed: {metrics['tool_responses']}")
    print(f"Error events observed: {metrics['errors']}")
    print(
        "Estimated hosted-model API charges: $0.00 for this test's "
        "configured local Ollama models; hardware and electricity excluded."
    )
    print(
        "Caveat: CrewAI sub-crew token usage may not be included unless "
        "it is separately instrumented."
    )
    print("=" * 78)

    session = await session_service.get_session(
        app_name=app_name,
        user_id=user_id,
        session_id=session_id,
    )

    if session:
        print("\n" + "=" * 78)
        print("FINAL WORKFLOW STATE")
        print("=" * 78)
        for key in (
            "email_context",
            "document_context",
            "calendar_context",
            "meeting_context",
            "research_context",
            "analysis_context",
            "final_briefing",
            "quality_status",
            "action_result",
        ):
            value = session.state.get(key)
            print(f"\n{key}:\n{value if value is not None else 'Not set'}")

    print("\nACTUAL MCP EXECUTION STATUS:")
    print(ACTUAL_MCP_RESULT or "No MCP task was requested by the workflow.")
    print("\n" + "=" * 78)
    print("OFFICEPILOT LOCAL LLM WORKFLOW TEST FINISHED")
    print("=" * 78)
    print(
        "Disclosure: LLM responses used local Ollama models. Research facts came "
        "from the local mock research fixture, and the MCP task server is a "
        "local mock—not an external task-management integration. The CLI "
        "approval gate is test-harness behavior, not ADK native resumable HITL."
    )


if __name__ == "__main__":
    asyncio.run(main())
